#!/usr/bin/env -S npx tsx
// Local dev tool — NEVER imported from src/, NEVER bundled into the app.
// Calls the Google Places API (New) Text Search endpoint to turn a theme +
// location into a hunt JSON file under src/hunts/, then regenerates
// src/hunts/index.ts so the app picks it up.
//
// Usage:
//   npm run generate-hunt -- --theme "Hot Dog Restaurants" --location "Downtown Seattle, WA" [--count 8] [--radius 150] [--id some-slug]

import { parseArgs } from 'node:util'
import { readdir, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import 'dotenv/config'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const HUNTS_DIR = path.resolve(__dirname, '../../src/hunts')
const INDEX_PATH = path.join(HUNTS_DIR, 'index.ts')

const DEFAULT_COUNT = 8
const MAX_COUNT = 20
const DEFAULT_RADIUS_METERS = 150

interface PlacesTextSearchResult {
  places?: Array<{
    id: string
    displayName?: { text?: string }
    formattedAddress?: string
    location?: { latitude: number; longitude: number }
  }>
}

function slugify(input: string): string {
  return input
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function uniqueSlug(base: string, taken: Set<string>): string {
  let slug = base || 'landmark'
  let n = 2
  while (taken.has(slug)) {
    slug = `${base}-${n}`
    n += 1
  }
  taken.add(slug)
  return slug
}

async function searchPlaces(theme: string, location: string, count: number) {
  const apiKey = process.env.GOOGLE_PLACES_API_KEY
  if (!apiKey) {
    console.error(
      'GOOGLE_PLACES_API_KEY is not set. Copy .env.example to .env and fill in a Places API (New) key — see README.md for setup steps.',
    )
    process.exit(1)
  }

  const res = await fetch('https://places.googleapis.com/v1/places:searchText', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'X-Goog-Api-Key': apiKey,
      'X-Goog-FieldMask': 'places.id,places.displayName,places.formattedAddress,places.location',
    },
    body: JSON.stringify({
      textQuery: `${theme} in ${location}`,
      maxResultCount: count,
    }),
  })

  if (!res.ok) {
    const body = await res.text()
    console.error(`Places API request failed: ${res.status} ${res.statusText}\n${body}`)
    process.exit(1)
  }

  const data = (await res.json()) as PlacesTextSearchResult
  return data.places ?? []
}

async function regenerateIndex() {
  const files = (await readdir(HUNTS_DIR))
    .filter((f) => f.endsWith('.json'))
    .sort()

  const importLines: string[] = []
  const varNames: string[] = []
  for (const file of files) {
    const base = path.basename(file, '.json')
    const varName = base
      .split('-')
      .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
      .join('')
      .replace(/^./, (c) => 'hunt' + c.toUpperCase())
    importLines.push(`import ${varName} from './${file}'`)
    varNames.push(varName)
  }

  const content = `// AUTO-GENERATED by \`npm run generate-hunt\` — do not hand-edit.
import type { Hunt } from './types'
${importLines.join('\n')}

export const HUNTS: Hunt[] = [${varNames.join(', ')}] as Hunt[]

export const getHuntById = (id: string): Hunt | undefined =>
  HUNTS.find((h) => h.id === id)
`

  await writeFile(INDEX_PATH, content)
  console.log(`Wrote ${path.relative(process.cwd(), INDEX_PATH)} (${files.length} hunt${files.length === 1 ? '' : 's'})`)
}

async function main() {
  const { values } = parseArgs({
    options: {
      theme: { type: 'string' },
      location: { type: 'string' },
      count: { type: 'string', default: String(DEFAULT_COUNT) },
      radius: { type: 'string', default: String(DEFAULT_RADIUS_METERS) },
      id: { type: 'string' },
    },
  })

  if (!values.theme || !values.location) {
    console.error('Usage: npm run generate-hunt -- --theme "<theme>" --location "<location>" [--count N] [--radius METERS] [--id slug]')
    process.exit(1)
  }

  const theme = values.theme
  const location = values.location
  const count = Math.min(MAX_COUNT, Math.max(1, Number(values.count) || DEFAULT_COUNT))
  const radius = Number(values.radius) || DEFAULT_RADIUS_METERS
  const huntId = values.id ? slugify(values.id) : slugify(`${theme} ${location}`)

  console.log(`Searching Places API for "${theme} in ${location}" (up to ${count} results)...`)
  const places = await searchPlaces(theme, location, count)

  if (places.length === 0) {
    console.error('No places found — try a different theme/location.')
    process.exit(1)
  }

  const takenIds = new Set<string>()
  const landmarks = places
    .filter((p) => p.displayName?.text && p.location)
    .map((p) => ({
      id: uniqueSlug(slugify(p.displayName!.text!), takenIds),
      name: p.displayName!.text!,
      lat: p.location!.latitude,
      lng: p.location!.longitude,
      address: p.formattedAddress ?? '',
      ...(radius !== DEFAULT_RADIUS_METERS ? { radiusMeters: radius } : {}),
    }))

  const hunt = {
    id: huntId,
    title: `${theme} — ${location}`,
    theme,
    locationLabel: location,
    landmarks,
  }

  const outPath = path.join(HUNTS_DIR, `${huntId}.json`)
  if (existsSync(outPath)) {
    console.error(`${path.relative(process.cwd(), outPath)} already exists — pass --id to pick a different slug.`)
    process.exit(1)
  }

  await writeFile(outPath, JSON.stringify(hunt, null, 2) + '\n')
  console.log(`Wrote ${path.relative(process.cwd(), outPath)} (${landmarks.length} landmarks)`)

  await regenerateIndex()
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
